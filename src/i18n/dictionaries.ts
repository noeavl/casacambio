export type Dictionary = typeof es;

export const dictionaries = { es, en } satisfies Record<'es' | 'en', Dictionary>;

type NestedKeyOf<T> = {
  [K in keyof T & string]: T[K] extends string ? `${K}` : `${K}.${keyof T[K] & string}`;
}[keyof T & string];

export type TranslationKey = NestedKeyOf<Dictionary>;

export type TranslationVars = Record<string, string | number>;

function interpolate(template: string, vars?: TranslationVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match,
  );
}

export function translate(dict: Dictionary, key: TranslationKey, vars?: TranslationVars): string {
  const [namespace, field] = key.split('.') as [keyof Dictionary, string];
  const section = dict[namespace] as Record<string, string>;
  const template = section?.[field] ?? key;
  return interpolate(template, vars);
}
